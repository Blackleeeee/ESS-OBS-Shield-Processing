function [data, hd] = rdSac_with_time(sacFile)

[data, hd, ok] = read_sac_endian(sacFile, 'ieee-le');

if ~ok
    [data, hd, ok] = read_sac_endian(sacFile, 'ieee-be');
end

if ~ok
    error( ...
        'Unable to determine SAC byte order or invalid SAC header: %s', ...
        sacFile);
end
end

function [data, hd, ok] = read_sac_endian(sacFile, machineFormat)

data = [];
hd = struct();
ok = false;

fid = fopen(sacFile, 'r', machineFormat);

if fid < 0
    error('Cannot open SAC file: %s', sacFile);
end

floatHeader = fread(fid, 70, 'single=>double');
intHeader   = fread(fid, 40, 'int32=>double');
charHeader  = fread(fid, 192, 'uint8=>uint8');
data        = fread(fid, inf, 'single=>single');

fclose(fid);

if numel(floatHeader) ~= 70 || ...
   numel(intHeader) ~= 40 || ...
   numel(charHeader) ~= 192

    return
end

delta  = floatHeader(1);
b      = floatHeader(6);

nzyear = intHeader(1);
nzjday = intHeader(2);
nzhour = intHeader(3);
nzmin  = intHeader(4);
nzsec  = intHeader(5);
nzmsec = intHeader(6);
npts   = intHeader(10);

if ~(isfinite(delta) && delta > 0 && delta < 100) || ...
   ~(nzyear >= 1900 && nzyear <= 2100) || ...
   ~(nzjday >= 1 && nzjday <= 366) || ...
   ~(nzhour >= 0 && nzhour <= 23) || ...
   ~(nzmin >= 0 && nzmin <= 59) || ...
   ~(nzsec >= 0 && nzsec <= 60) || ...
   ~(nzmsec >= 0 && nzmsec <= 999) || ...
   ~(npts > 0)

    return
end

if npts ~= numel(data)
    warning([ ...
        'SAC header NPTS (%d) differs from the number of samples ', ...
        'read from file (%d): %s'], ...
        npts, ...
        numel(data), ...
        sacFile);
end

referenceTime = datenum( ...
    nzyear, ...
    1, ...
    1, ...
    nzhour, ...
    nzmin, ...
    nzsec + nzmsec / 1000);

startTime = referenceTime + ...
    (nzjday - 1) + ...
    b / 86400;

Fs = 1 / delta;

endTime = startTime + ...
    (numel(data) - 1) / (Fs * 86400);

hd.delta = delta;
hd.Fs = Fs;
hd.b = b;
hd.npts = npts;
hd.startTime = startTime;
hd.endTime = endTime;
hd.machineFormat = machineFormat;
hd.floatHeader = floatHeader;
hd.intHeader = intHeader;

ok = true;
end

function yLim = get_log_ylim(ydata)

ydata = ydata(isfinite(ydata) & ydata > 0);

if isempty(ydata)
    error('No positive finite RMS values are available for Y-axis limits.');
end

lowerExp = floor(2 * log10(min(ydata))) / 2;
upperExp = ceil(2 * log10(max(ydata))) / 2;

if upperExp <= lowerExp
    upperExp = lowerExp + 0.5;
end

yLim = 10 .^ [lowerExp, upperExp];
end
