%% Fig2_RMS.m
% =========================================================================
% Calculate 30-minute RMS values from continuous, response-corrected
% acceleration SAC data and generate the RMS panels used in Figure 2.
%
% Expected repository layout:
%
% Test_SUSTech/
% ├── ESS_OBS_Shield_Data_v1.0/
% │   ├── Pro_Seismic_acceleration_v1.0/
% │   └── Raw_Current_Tide_v1.0/
% │       ├── dataforzzh.mat
% │       └── Tide_UTC.txt
% │
% └── ESS_OBS_Shield_Scripts_v1.0/
%     └── Fig2_RMS.m
%
% Outputs:
%   outputs/Processed_RMS_v1.0/Results_RMS.mat
%   outputs/Figure2/*.tif
%
% The RMS calculation and plotting logic are retained from the original
% analysis script. Only repository-relative paths and input checks were
% introduced for public release.
% =========================================================================

clc;
clear;
close all;

%% Repository-relative paths

script_file = mfilename('fullpath');

if isempty(script_file)
    error(['MATLAB cannot determine the location of Fig2_RMS.m. ', ...
           'Run the saved script file rather than an unsaved editor buffer.']);
end

script_root  = fileparts(script_file);
project_root = fileparts(script_root);

data_root = fullfile( ...
    project_root, ...
    'ESS_OBS_Shield_Data_v1.0');

rd4data = fullfile( ...
    data_root, ...
    'Pro_Seismic_acceleration_v1.0');

current_tide_dir = fullfile( ...
    data_root, ...
    'Raw_Current_Tide_v1.0');

current_mat_file = fullfile( ...
    current_tide_dir, ...
    'dataforzzh.mat');

tide_file = fullfile( ...
    current_tide_dir, ...
    'Tide_UTC.txt');

rms_output_dir = fullfile( ...
    script_root, ...
    'outputs', ...
    'Processed_RMS_v1.0');

figure_output_dir = fullfile( ...
    script_root, ...
    'outputs', ...
    'Figure2');

required_paths = {
    rd4data
    current_mat_file
    tide_file
};

for i_path = 1:numel(required_paths)
    this_path = required_paths{i_path};

    if ~(isfolder(this_path) || isfile(this_path))
        error('Required input not found: %s', this_path);
    end
end

if ~exist(rms_output_dir, 'dir')
    mkdir(rms_output_dir);
end

if ~exist(figure_output_dir, 'dir')
    mkdir(figure_output_dir);
end

%% Basic settings

stations = {'T01', 'T02'};
Fs_expected = 100;
winLen = 1800;

% RMS calculation range:
% Each value below is the start time of a 30 min RMS window.
calc_start_date = datenum(2025, 3, 14, 0, 0, 0);
calc_end_date   = datenum(2025, 3, 31, 23, 0, 0);

% Plotting/statistical-display range:
% Edge periods affected by the response-removal taper are excluded.
plot_start_date = datenum(2025, 3, 15, 0, 0, 0);
plot_end_date   = datenum(2025, 3, 30, 23, 0, 0);

if plot_start_date < calc_start_date || ...
   plot_end_date > calc_end_date

    error('The plotting range must lie inside the RMS calculation range.');
end

%% Current data

current_data = load(current_mat_file);

required_current_variables = {
    'rcm_time'
    'rcm_hor_vel_true'
};

for i_var = 1:numel(required_current_variables)
    variable_name = required_current_variables{i_var};

    if ~isfield(current_data, variable_name)
        error( ...
            'Required variable "%s" is absent from %s.', ...
            variable_name, ...
            current_mat_file);
    end
end

% Original MAT-file time is Beijing time; convert to UTC.
rcm_time = current_data.rcm_time(:) - 8 / 24;

% Original current speed is in cm/s; convert to m/s.
rcm_vel = current_data.rcm_hor_vel_true(:) / 100;

%% Tide data

opts = detectImportOptions( ...
    tide_file, ...
    'Delimiter', '\t');

opts.VariableNamesLine = 1;
opts.DataLines = [2 Inf];

tide_raw = readtable(tide_file, opts);

Time_Tide = datenum(datetime( ...
    tide_raw{:, 1}, ...
    'InputFormat', 'yyyy-MM-dd HH:mm:ss'));

Level_Tide = tide_raw{:, 2} / 100;

%% RMS calculation

Results = struct( ...
    'station', {}, ...
    'TIME', {}, ...
    'CURR', {}, ...
    'BH_RMS', {}, ...
    'BZ_RMS', {}, ...
    'BH_BZ', {});

window_step_day = winLen / 86400;
window_start_times = ...
    calc_start_date:window_step_day:calc_end_date;

nWin = numel(window_start_times);

for s = 1:numel(stations)

    sta = stations{s};
    fprintf('\nStation %s\n', sta);

    sacE = dir(fullfile( ...
        rd4data, ...
        sprintf('ZS.%s.LC.BHE*.SAC', sta)));

    sacN = dir(fullfile( ...
        rd4data, ...
        sprintf('ZS.%s.LC.BHN*.SAC', sta)));

    sacZ = dir(fullfile( ...
        rd4data, ...
        sprintf('ZS.%s.LC.BHZ*.SAC', sta)));

    if isempty(sacE) || isempty(sacN) || isempty(sacZ)
        warning('Station %s is missing one or more SAC components. Skipping.', sta);
        continue
    end

    if numel(sacE) > 1 || numel(sacN) > 1 || numel(sacZ) > 1
        warning([ ...
            'Station %s has multiple matching SAC files. ', ...
            'Only the first matching file for each component is used.'], ...
            sta);
    end

    fileE = fullfile(rd4data, sacE(1).name);
    fileN = fullfile(rd4data, sacN(1).name);
    fileZ = fullfile(rd4data, sacZ(1).name);

    [E, hdE] = rdSac_with_time(fileE);
    [N, hdN] = rdSac_with_time(fileN);
    [Z, hdZ] = rdSac_with_time(fileZ);

    %% Sampling-rate checks

    Fs = hdE.Fs;

    if abs(hdN.Fs - Fs) > 1e-6 || ...
       abs(hdZ.Fs - Fs) > 1e-6

        error( ...
            '%s: the sampling rates of the three components are inconsistent.', ...
            sta);
    end

    if abs(Fs - Fs_expected) > 1e-6
        warning( ...
            '%s: actual sampling rate is %.8f Hz, not %.8f Hz.', ...
            sta, ...
            Fs, ...
            Fs_expected);
    end

    samplesPerWin = round(winLen * Fs);

    fprintf( ...
        '  BHE: %s to %s, Fs = %.6f Hz\n', ...
        datestr(hdE.startTime, 'yyyy-mm-dd HH:MM:SS.FFF'), ...
        datestr(hdE.endTime,   'yyyy-mm-dd HH:MM:SS.FFF'), ...
        Fs);

    fprintf( ...
        '  BHN: %s to %s, Fs = %.6f Hz\n', ...
        datestr(hdN.startTime, 'yyyy-mm-dd HH:MM:SS.FFF'), ...
        datestr(hdN.endTime,   'yyyy-mm-dd HH:MM:SS.FFF'), ...
        Fs);

    fprintf( ...
        '  BHZ: %s to %s, Fs = %.6f Hz\n', ...
        datestr(hdZ.startTime, 'yyyy-mm-dd HH:MM:SS.FFF'), ...
        datestr(hdZ.endTime,   'yyyy-mm-dd HH:MM:SS.FFF'), ...
        Fs);

    %% Preallocate output arrays

    TIME   = window_start_times;
    CURR   = nan(1, nWin);
    BH_RMS = nan(1, nWin);
    BZ_RMS = nan(1, nWin);
    BH_BZ  = nan(1, nWin);

    for w = 1:nWin

        t0 = window_start_times(w);

        idxE1 = round( ...
            (t0 - hdE.startTime) * 86400 * Fs) + 1;

        idxN1 = round( ...
            (t0 - hdN.startTime) * 86400 * Fs) + 1;

        idxZ1 = round( ...
            (t0 - hdZ.startTime) * 86400 * Fs) + 1;

        idxE2 = idxE1 + samplesPerWin - 1;
        idxN2 = idxN1 + samplesPerWin - 1;
        idxZ2 = idxZ1 + samplesPerWin - 1;

        if idxE1 < 1 || idxN1 < 1 || idxZ1 < 1 || ...
           idxE2 > numel(E) || ...
           idxN2 > numel(N) || ...
           idxZ2 > numel(Z)

            warning( ...
                '%s: no complete three-component window at %s. Assigned NaN.', ...
                sta, ...
                datestr(t0, 'yyyy-mm-dd HH:MM:SS'));

            continue
        end

        E_win = double(E(idxE1:idxE2));
        N_win = double(N(idxN1:idxN2));
        Z_win = double(Z(idxZ1:idxZ2));

        valid = ...
            isfinite(E_win) & ...
            isfinite(N_win) & ...
            isfinite(Z_win);

        if mean(valid) < 0.99
            warning( ...
                '%s: valid-data fraction < 99%% at %s. Assigned NaN.', ...
                sta, ...
                datestr(t0, 'yyyy-mm-dd HH:MM:SS'));

            continue
        end

        % Linear detrending only; no Hann taper is applied before RMS.
        E_prep = detrend(E_win, 'linear');
        N_prep = detrend(N_win, 'linear');
        Z_prep = detrend(Z_win, 'linear');

        BH = sqrt(E_prep.^2 + N_prep.^2);

        BH_RMS(w) = rms(BH);
        BZ_RMS(w) = rms(Z_prep);
        BH_BZ(w)  = BH_RMS(w) / BZ_RMS(w);

        % Current speed is interpolated at the start time of each window.
        CURR(w) = interp1( ...
            rcm_time, ...
            rcm_vel, ...
            t0, ...
            'linear', ...
            NaN);
    end

    Results(s) = struct( ...
        'station', sta, ...
        'TIME', TIME, ...
        'CURR', CURR, ...
        'BH_RMS', BH_RMS, ...
        'BZ_RMS', BZ_RMS, ...
        'BH_BZ', BH_BZ);
end

save( ...
    fullfile(rms_output_dir, 'Results_RMS.mat'), ...
    'Results', ...
    'calc_start_date', ...
    'calc_end_date', ...
    'plot_start_date', ...
    'plot_end_date');

%% Plot Figure 2 RMS panels

plot_all_figures( ...
    Results, ...
    plot_start_date, ...
    plot_end_date, ...
    figure_output_dir, ...
    Time_Tide, ...
    Level_Tide);

fprintf('\nDone\n');

