function [StartTime, EndTime] = read_tidal_events(eventFile)
% Read a tab-delimited tidal-stage event file.
%
% Expected columns:
%   1. Event identifier or label
%   2. Start time: yyyy-MM-dd HH:mm:ss
%   3. End time:   yyyy-MM-dd HH:mm:ss

opts = detectImportOptions( ...
    eventFile, ...
    'Delimiter', '\t');

opts.VariableTypes = {
    'string'
    'datetime'
    'datetime'
};

opts = setvaropts( ...
    opts, ...
    2, ...
    'InputFormat', 'yyyy-MM-dd HH:mm:ss');

opts = setvaropts( ...
    opts, ...
    3, ...
    'InputFormat', 'yyyy-MM-dd HH:mm:ss');

Tab = readtable(eventFile, opts);

StartTime = datenum(Tab{:, 2});
EndTime   = datenum(Tab{:, 3});
end

function mask = in_periods(T, StartTime, EndTime)
% Check whether each time belongs to one or more event periods.

mask = false(size(T));

for i = 1:length(StartTime)
    mask = mask | ...
        (T >= StartTime(i) & T < EndTime(i));
end
end

function [x, y] = extract_freqtime_samples( ...
    PSD_freq, PSDdiff, Speed, idxStage, f1, f2)
% Extract all frequency-time PSDdiff samples in one frequency band and
% duplicate the matched current speed across frequency rows.

fidx = PSD_freq >= f1 & PSD_freq <= f2;

if ~any(fidx)
    x = [];
    y = [];
    return
end

tidx = idxStage & ~isnan(Speed);

if ~any(tidx)
    x = [];
    y = [];
    return
end

D = PSDdiff(fidx, tidx);
S = Speed(tidx);

S_mat = repmat( ...
    S(:).', ...
    size(D, 1), ...
    1);

x = S_mat(:);
y = D(:);

valid = ~isnan(x) & ~isnan(y);

x = x(valid);
y = y(valid);
end

function [xPlot, yPlot] = thin_points(x, y, maxN)
% Randomly thin scatter points for display.
% Retained from the original script although not currently called.

n = numel(x);

if n <= maxN
    xPlot = x;
    yPlot = y;
    return
end

rng(1);
idx = randperm(n, maxN);

xPlot = x(idx);
yPlot = y(idx);
end

function Stat = plot_binned_median_iqr_xy( ...
    ax, X, Y, edges, color_rgb, minN, line_width, shade_alpha)
% Calculate and plot the median and interquartile range in current-speed
% bins.

hold(ax, 'on');

nB = length(edges) - 1;

xc   = nan(1, nB);
medv = nan(1, nB);
q1v  = nan(1, nB);
q3v  = nan(1, nB);
nv   = zeros(1, nB);

for i = 1:nB

    idb = ...
        X >= edges(i) & ...
        X < edges(i + 1) & ...
        ~isnan(X) & ...
        ~isnan(Y);

    nv(i) = sum(idb);

    if nv(i) < minN
        continue
    end

    vals = Y(idb);

    xc(i) = ...
        (edges(i) + edges(i + 1)) / 2;

    medv(i) = median( ...
        vals, ...
        'omitnan');

    q1v(i) = prctile( ...
        vals, ...
        25);

    q3v(i) = prctile( ...
        vals, ...
        75);
end

valid = ~isnan(xc) & ~isnan(medv);

Stat.xc     = xc;
Stat.median = medv;
Stat.q1     = q1v;
Stat.q3     = q3v;
Stat.N      = nv;

if sum(valid) < 2
    return
end

x   = xc(valid);
med = medv(valid);
q1  = q1v(valid);
q3  = q3v(valid);

patch( ...
    ax, ...
    [x fliplr(x)], ...
    [q1 fliplr(q3)], ...
    color_rgb, ...
    'FaceAlpha', shade_alpha, ...
    'EdgeColor', 'none', ...
    'HandleVisibility', 'off');

plot( ...
    ax, ...
    x, ...
    med, ...
    '-', ...
    'Color', color_rgb, ...
    'LineWidth', line_width, ...
    'HandleVisibility', 'off');

plot( ...
    ax, ...
    x, ...
    med, ...
    'o', ...
    'MarkerFaceColor', color_rgb, ...
    'MarkerEdgeColor', 'k', ...
    'MarkerSize', 4.2, ...
    'LineWidth', 0.5, ...
    'HandleVisibility', 'off');
end
